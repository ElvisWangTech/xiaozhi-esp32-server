-- 系统错误兜底话术调整（2026-11-05）
-- 原话术「主人，小智现在有点忙，我们稍后再试吧。」的问题：
--   1. 「主人」是通用默认称呼，设备已让用户设置过自己的称呼，不该再叫主人；
--   2. 「小智」是公共名字，助手有用户起的昵称，不该自称小智；
--   3. 个人助手不该用「有点忙」当借口，直接说明后台服务出了问题更诚实。
-- 也不能改成「再说一遍」：provider 全挂时用户重复说多少遍都一样，
-- 只会加深挫败感。所以只如实说明情况，不给重试暗示。
-- 新话术用 {title} 占位用户称呼（由 xiaozhi-server 从角色设定解析，未设置时自动省略）。
-- -------------------------------------------------------

UPDATE `sys_params`
SET `param_value` = '{title}抱歉，我的后台服务出了一点问题，暂时帮不了您。',
    `remark` = '系统错误时的回复，{title} 会替换为用户称呼',
    `updater` = 1,
    `update_date` = NOW()
WHERE `param_code` = 'system_error_response';
